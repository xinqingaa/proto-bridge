#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const sourceRoot = path.join(packageRoot, 'src');
const generatedPath = path.join(sourceRoot, 'generated-build-info.ts');
const packageJson = JSON.parse(
  await readFile(path.join(packageRoot, 'package.json'), 'utf8'),
);
const files = [
  'package.json',
  ...(await sourceFiles(sourceRoot)).map((file) =>
    path.relative(packageRoot, file).split(path.sep).join('/'),
  ),
].sort();
const hash = createHash('sha256');
for (const relativePath of files) {
  hash.update(relativePath);
  hash.update('\0');
  hash.update(await readFile(path.join(packageRoot, relativePath)));
  hash.update('\0');
}

const output = `// Generated by scripts/generate-build-info.mjs. Do not edit manually.\n` +
  `export const MCP_BUILD_FINGERPRINT = ${JSON.stringify(`sha256:${hash.digest('hex')}`)} as const;\n` +
  `export const MCP_PACKAGE_VERSION = ${JSON.stringify(packageJson.version)} as const;\n`;
await writeFile(generatedPath, output, 'utf8');

async function sourceFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await sourceFiles(absolute));
    else if (entry.name.endsWith('.ts') && absolute !== generatedPath) files.push(absolute);
  }
  return files;
}
