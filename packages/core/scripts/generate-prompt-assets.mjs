import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const promptDir = path.resolve(scriptDir, '../src/v2/prompts');
const names = [
  'handoff-consumer',
  'target-contract',
  'implementation-discipline',
  'verification',
  'final-report',
];

const entries = [];
for (const name of names) {
  const text = await readFile(path.join(promptDir, `${name}.md`), 'utf8');
  entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(text)},`);
}

await mkdir(promptDir, { recursive: true });
await writeFile(
  path.join(promptDir, 'generated-assets.ts'),
  `// Generated by packages/core/scripts/generate-prompt-assets.mjs.\n` +
    `// Edit the adjacent Markdown files, then run the generator.\n` +
    `export const PROMPT_ASSETS = {\n${entries.join('\n')}\n} as const;\n`,
  'utf8',
);
