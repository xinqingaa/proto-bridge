#!/usr/bin/env node
import { readFile, mkdir, writeFile, readdir, rm } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { repoRoot, optionValue } from './lib/pb-script-utils.mjs';
import { parseSvgArtwork } from '../apps/pbwork/src/design-system/components/_shared/svg-artwork.mjs';

const sourcePath = path.join(repoRoot, 'apps/pbwork/src/design-system/components/_shared/glyph-artwork.json');
export async function exportFlutterIcons({targetRoot = path.join(repoRoot, 'apps/flutter_pb_app'), prototype, check = false} = {}) {
  if (prototype && !/^[a-z][a-z0-9-]*$/.test(prototype)) throw new Error('Invalid prototype id');
  if (prototype) await readFile(path.join(repoRoot, 'apps/pbwork/src/prototypes', prototype, 'prototype.ts'));
  const artwork = JSON.parse(await readFile(sourcePath, 'utf8'));
  const entries = await Promise.all(Object.entries(artwork.icons)
    .filter(([, glyph]) => !prototype || glyph.owner === 'shared' || glyph.owner === prototype)
    .map(async ([id, entry]) => [id, {...entry, ...parseSvgArtwork(await readFile(path.join(path.dirname(sourcePath), entry.file), 'utf8'))}]));
  const output = path.join(targetRoot, 'assets/icons');
  const manifest = {
    scope: prototype ? {prototype} : {all: true},
    sourceDigest: createHash('sha256').update(JSON.stringify({entries})).digest('hex'),
    icons: entries.map(([id, glyph]) => ({id, owner: glyph.owner, width: glyph.width, height: glyph.height, scale: 3, colorMode: glyph.colorMode, file: `${id}.png`})),
  };
  const dartName = (name) => name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
  const intrinsicNames = entries.filter(([, glyph]) => glyph.colorMode === 'intrinsic').map(([id]) => dartName(id));
  const colorDeclaration = intrinsicNames.length
    ? `const _intrinsicColorIcons = <CommonIconName>{\n${intrinsicNames.map(name => `  CommonIconName.${name},`).join('\n')}\n};\n`
    : 'const _intrinsicColorIcons = <CommonIconName>{};\n';
  const dart = `// Generated by export-flutter-icons.mjs. Edit PBWork SVG artwork instead.\npart of 'icon.dart';\n\nenum CommonIconName {\n${entries.map(([id]) => `  ${dartName(id)},`).join('\n')}\n}\n\n${colorDeclaration}`;
  const manifestPath = path.join(targetRoot, 'proto-bridge.icons.json');
  const dartPath = path.join(targetRoot, 'lib/common/widgets/action/generated_icon_names.dart');
  if (check) {
    if (await readFile(manifestPath, 'utf8') !== JSON.stringify(manifest, null, 2) + '\n') throw new Error('Icon scope or artwork drifted; rerun export-flutter-icons.mjs');
    if (await readFile(dartPath, 'utf8') !== dart) throw new Error('Dart icon identities drifted');
    for (const icon of manifest.icons) {
      const png = await readFile(path.join(output, icon.file));
      if (png.readUInt32BE(16) !== icon.width * icon.scale || png.readUInt32BE(20) !== icon.height * icon.scale) throw new Error(`Wrong raster dimensions: ${icon.id}`);
    }
    return;
  }
  const require = createRequire(path.join(repoRoot, 'apps/pbwork/package.json'));
  const { chromium } = require('@playwright/test');
  const browser = await chromium.launch({headless: true});
  try {
    const page = await browser.newPage();
    await mkdir(output, {recursive: true});
    for (const [id, glyph] of entries) {
      const png = await page.evaluate(async ({artwork, glyph, id}) => {
        const source = glyph.svg;
        const doc = new DOMParser().parseFromString(source, 'image/svg+xml');
        if (doc.querySelector('parsererror')) throw new Error(`Invalid SVG: ${id}`);
        for (const element of doc.querySelectorAll('*')) {
          if (['script','foreignObject','image'].includes(element.localName)) throw new Error(`Expected native vector SVG: ${id}`);
          for (const attr of element.attributes) {
            if (/^on/i.test(attr.name) || attr.name !== 'xmlns' && /(?:https?:|data:|javascript:)/i.test(attr.value)) throw new Error(`External or executable SVG: ${id}`);
          }
        }
        const image = new Image();
        image.src = URL.createObjectURL(new Blob([source], {type: 'image/svg+xml'}));
        try {
          await image.decode();
          const canvas = document.createElement('canvas');
          canvas.width = glyph.width * 3;
          canvas.height = glyph.height * 3;
          canvas.getContext('2d').drawImage(image, 0, 0, canvas.width, canvas.height);
          return canvas.toDataURL('image/png').split(',')[1];
        } finally { URL.revokeObjectURL(image.src); }
      }, {artwork, glyph, id});
      await writeFile(path.join(output, `${id}.png`), Buffer.from(png, 'base64'));
    }
    // Prune only generated PNGs after successful rendering; unrelated files survive.
    const wanted = new Set(manifest.icons.map((icon) => icon.file));
    const managed = new Set(Object.keys(artwork.icons).map((id) => `${id}.png`));
    try {
      const previous = JSON.parse(await readFile(manifestPath, 'utf8'));
      for (const icon of previous.icons) managed.add(icon.file);
    } catch (error) { if (error.code !== 'ENOENT') throw error; }
    for (const file of await readdir(output)) if (managed.has(file) && !wanted.has(file)) await rm(path.join(output, file));
    await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
    await writeFile(dartPath, dart);
    process.stdout.write(`Exported ${entries.length} PBWork SVG icons at 3x.\n`);
  } finally { await browser.close(); }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await exportFlutterIcons({targetRoot: optionValue(process.argv, '--target'), prototype: optionValue(process.argv, '--prototype'), check: process.argv.includes('--check')});
}
