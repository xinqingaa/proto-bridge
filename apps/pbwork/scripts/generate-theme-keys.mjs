import { readFileSync, readdirSync, mkdirSync, writeFileSync } from "node:fs";
import { URL, fileURLToPath } from "node:url";
import path from "node:path";
import { PB_STYLE_SLOTS } from "../src/design-system/theme/slots.ts";
import { assembleThemeKeyCatalog } from "../src/design-system/theme/key-catalog.ts";

export const pbworkRoot = fileURLToPath(new URL("../", import.meta.url));
export function generateThemeKeys(slots) {
  const read = (name) =>
    JSON.parse(
      readFileSync(path.join(pbworkRoot, "src/design-system", name), "utf8"),
    );
  const contracts = readdirSync(
    path.join(pbworkRoot, "src/design-system/components/contracts"),
  )
    .filter((n) => n.endsWith(".json"))
    .sort()
    .map((n) => read("components/contracts/" + n));
  const catalog = assembleThemeKeyCatalog(contracts);
  const constants = read("theme/constants.json").constants;
  const keys = catalog.keys;
  const families = {
    SemanticKey: keys.filter((k) => k.tier === "semantic"),
    ComponentKey: keys.filter((k) => k.tier === "component"),
    BindableKey: keys.filter((k) => k.bindable),
    ConstantKey: constants,
    LengthConstantKey: constants.filter((key) => key.valueType === "length"),
    ColorKey: keys.filter((k) => k.bindable && k.valueType === "color"),
    SpaceKey: keys.filter(
      (k) =>
        k.bindable && (k.id.startsWith("spacing.") || k.id.endsWith(".gap")),
    ),
    RadiusKey: keys.filter((k) => k.bindable && k.id.startsWith("radius.")),
    TypographyKey: keys.filter(
      (k) => k.bindable && k.valueType === "typography",
    ),
    ElevationKey: keys.filter((k) => k.bindable && k.valueType === "shadow"),
    BorderKey: keys.filter((k) => k.bindable && k.valueType === "border"),
    SizeKey: keys.filter((k) => k.bindable && k.valueType === "length"),
  };
  const lines = ["// Generated by pnpm ds:keys:generate. Do not edit."];
  for (const [family, entries] of Object.entries(families))
    lines.push(
      `export type ${family} = ${
        entries
          .map((k) => JSON.stringify(k.id))
          .sort()
          .join(" | ") || "never"
      };`,
    );
  lines.push("export interface PbStyleInput {");
  for (const [slot, spec] of Object.entries(slots)) {
    const type =
      spec.family +
      (spec.pair
        ? ` | readonly [${spec.family} | LengthConstantKey, ${spec.family} | LengthConstantKey]`
        : "") +
      (["SpaceKey", "SizeKey"].includes(spec.family)
        ? " | LengthConstantKey"
        : "") +
      (spec.literals ?? []).map((v) => " | " + JSON.stringify(v)).join("");
    lines.push(`  ${slot}?: ${type};`);
  }
  lines.push(
    "}",
    `export const bindableKeys = ${JSON.stringify(families.BindableKey.map((k) => k.id).sort(), null, 2)} as const;`,
    "",
  );
  return lines.join("\n");
}
export function writeThemeKeys(slots) {
  const dir = path.join(pbworkRoot, "src/design-system/theme/generated");
  mkdirSync(dir, { recursive: true });
  writeFileSync(path.join(dir, "keys.ts"), generateThemeKeys(slots));
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  writeThemeKeys(PB_STYLE_SLOTS);
